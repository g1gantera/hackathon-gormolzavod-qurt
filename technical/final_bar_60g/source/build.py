def block(a,x,y,width,s,size=2.4,leading=3.25,bold=False):
    """Wrap with the exact Open Sans font metrics; no rasterized text."""
    lines=[];current=""
    for word in s.split():
        test=(current+" "+word).strip()
        if current and pdfmetrics.stringWidth(test,"Bold" if bold else "Regular",size)>width:
            lines.append(current);current=word
        else:current=test
    if current:lines.append(current)
    for row in lines:a.append(t(x,y,row,size,bold));y+=leading
    return y

